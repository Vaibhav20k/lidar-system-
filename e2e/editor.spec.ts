import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';

test('create, edit, validate, persist, export, sync and recover a conflict', async ({ page, request }) => {
  const name = 'E2E room ' + Date.now(), remoteName = 'Remote ' + Date.now();
  const errors: string[]=[]; page.on('pageerror',error=>errors.push(error.message));
  await page.goto('/');
  await expect(page.getByText('SAMPLE · NOT A SCAN')).toBeVisible();
  await page.getByRole('button',{name:'Create a room',exact:true}).click();
  await page.getByRole('textbox',{name:'Room name'}).fill(name);
  await page.getByRole('spinbutton',{name:'Width (m)'}).fill('6');
  await page.getByRole('button',{name:'Create room',exact:true}).click();
  await expect(page.getByRole('heading',{name:name,exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Floorplan',exact:true}).click();
  await expect(page.getByRole('button',{name:'Select wall 1, 6.00 meters'})).toBeVisible();
  await page.getByRole('button',{name:'Add door or window'}).click();
  await page.getByRole('dialog').getByRole('spinbutton',{name:'Width m',exact:true}).fill('7');
  await page.getByRole('button',{name:'Add to room'}).click();
  await expect(page.getByRole('dialog').getByRole('alert')).toContainText('beyond its wall');
  await page.getByRole('dialog').getByRole('spinbutton',{name:'Width m',exact:true}).fill('1');
  await page.getByRole('button',{name:'Add to room'}).click();
  await expect(page.getByRole('dialog')).not.toBeVisible();
  await page.getByRole('button',{name:'Save',exact:true}).click();
  await expect(page.getByText('Room saved on this device.')).toBeVisible();
  await page.reload();
  await expect(page.getByRole('heading',{name:name,exact:true})).toBeVisible();
  await expect(page.getByRole('button',{name:'Door Wall 1 1.00 m'})).toBeVisible();
  await page.getByRole('button',{name:'Export',exact:true}).click();
  const jsonPromise=page.waitForEvent('download');
  await page.getByRole('button',{name:/JSON Editable room/}).click();
  const json=await jsonPromise, room=JSON.parse(await readFile((await json.path())!,'utf8'));
  expect(room.openings[0].width).toBe(1); expect(room.floor[1].x).toBe(6);
  const glbPromise=page.waitForEvent('download');
  await page.getByRole('button',{name:/GLB 3D model/}).click();
  const glb=await readFile((await (await glbPromise).path())!);
  expect(glb.subarray(0,4).toString()).toBe('glTF'); expect(glb.readUInt32LE(4)).toBe(2); expect(glb.readUInt32LE(8)).toBe(glb.length);
  const svgPromise=page.waitForEvent('download'); await page.getByRole('button',{name:/SVG Vector floorplan/}).click();
  const svg=await readFile((await (await svgPromise).path())!,'utf8'); expect(svg).toContain('http://www.w3.org/2000/svg'); expect(svg).toContain('6.00 m');
  await page.getByRole('button',{name:'Close dialog'}).click();
  await page.getByRole('button',{name:'Settings & sync'}).click();
  await page.getByRole('button',{name:'Sync this room'}).click();
  await expect(page.getByRole('dialog').getByRole('status')).toHaveText('Room saved and synced.');
  const stored=await (await request.get(`/api/rooms/${room.id}`)).json(); expect(stored.room.name).toBe(name); expect(stored.revision).toBe(1);
  await request.put(`/api/rooms/${room.id}`,{data:{room:{...stored.room,name:remoteName},revision:1}});
  await page.getByRole('button',{name:'Sync this room'}).click();
  await expect(page.getByRole('dialog').getByRole('alert')).toContainText('newer version');
  await page.getByRole('button',{name:'Pull rooms',exact:true}).click();
  await expect(page.getByRole('dialog').getByRole('status')).toContainText('preserved');
  await page.getByRole('button',{name:'Close dialog'}).click();
  await expect(page.getByRole('button',{name:new RegExp(name + '.*local copy')})).toBeVisible();
  await page.getByRole('button',{name:new RegExp(remoteName + '.*Manual')}).click();
  await expect(page.getByRole('heading',{name:remoteName,exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Settings & sync'}).click(); await page.getByRole('button',{name:'Sync this room'}).click();
  await expect(page.getByRole('dialog').getByRole('status')).toHaveText('Room saved and synced.');
  await page.getByRole('button',{name:'Close dialog'}).click();
  await page.getByRole('button',{name:'Import room JSON'}).setInputFiles({name:'round-trip.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(room))});
  await expect(page.getByRole('heading',{name:name,exact:true})).toBeVisible();
  await expect(page.getByText('Room imported as a new copy.')).toBeVisible();
  await page.getByRole('button',{name:'3D model',exact:true}).click();
  await expect(page.getByRole('img',{name:/Interactive 3D room/})).toBeVisible();
  await page.screenshot({path:'test-results/editor-desktop.png',fullPage:true});
  expect(errors).toEqual([]);
});

test('mobile layout and honest browser capability fallback',async({page})=>{
  await page.setViewportSize({width:393,height:852}); await page.goto('/');
  await page.getByRole('button',{name:'Open navigation'}).click(); await page.getByRole('button',{name:'Scan a room',exact:true}).click();
  await expect(page.getByRole('button',{name:'Start scanning',exact:true})).toBeDisabled();
  await expect(page.getByText('Scan from the installed mobile app')).toBeVisible();
  await page.getByRole('button',{name:'Create a room with measurements instead'}).click();
  await page.getByRole('button',{name:'Create room',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Living room',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Floorplan',exact:true}).click();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  await page.screenshot({path:'test-results/editor-mobile.png',fullPage:true});
});
